/** 构造 Cloudflare Dashboard 各资源的跳转 URL。accountId 缺失时返回 null。 */
function cfLinks(infra: AdminInfraConfig) {
  const acct = infra.cloudflare.accountId;
  if (!acct) return null;
  const base = `https://dash.cloudflare.com/${acct}`;
  const { workerName, d1DatabaseId, kvNamespaceId, sessionKvNamespaceId, accessApplicationId } =
    infra.cloudflare;
  return {
    dashboard: base,
    worker: workerName
      ? `${base}/workers/services/view/${workerName}/production`
      : `${base}/workers`,
    d1: d1DatabaseId ? `${base}/workers/d1/databases/${d1DatabaseId}/tables` : `${base}/workers/d1`,
    kv: kvNamespaceId
      ? `${base}/workers/kv/namespaces/${kvNamespaceId}`
      : `${base}/workers/kv/namespaces`,
    sessionKv: sessionKvNamespaceId
      ? `${base}/workers/kv/namespaces/${sessionKvNamespaceId}`
      : `${base}/workers/kv/namespaces`,
    access: accessApplicationId
      ? `${base}/zero-trust/access/apps/${accessApplicationId}`
      : `${base}/zero-trust/access/apps`,
    turnstile: `${base}/turnstile`,
  };
}

/** 构造 Supabase Dashboard 各资源的跳转 URL。 */
function sbLinks(infra: AdminInfraConfig) {
  const ref = infra.supabase.projectRef;
  if (!ref) return null;
  const base = `https://supabase.com/dashboard/project/${ref}`;
  return {
    project: base,
    storage: `${base}/storage/buckets`,
    settings: `${base}/settings/general`,
  };
}

