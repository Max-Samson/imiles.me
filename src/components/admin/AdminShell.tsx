/** 复制按钮图标（带反馈态） */
function CopyBtn({
  text,
  id,
  copiedKey,
  onCopy,
}: {
  text: string;
  id: string;
  copiedKey: string | null;
  onCopy: (text: string, key: string) => void;
}) {
  return (
    <button
      type="button"
      onClick={() => onCopy(text, id)}
      title="复制"
      className="shrink-0 text-muted-foreground hover:text-foreground transition-colors"
    >
      {copiedKey === id ? (
        <Check className="size-3 text-emerald-500" />
      ) : (
        <Copy className="size-3" />
      )}
    </button>
  );
}

/** 外链跳转按钮 */
function LinkBtn({ href, label }: { href: string; label: string }) {
  return (
    <a
      href={href}
      target="_blank"
      rel="noopener noreferrer"
      title={label}
      className="inline-flex items-center gap-0.5 text-[10px] font-medium text-primary hover:underline underline-offset-2 shrink-0"
    >
      {label}
      <ExternalLink className="size-2.5" />
    </a>
  );
}

/** 规格行：标签 + 值 + 可选复制 + 可选跳转 */
function SpecRow({
  label,
  value,
  mono = true,
  copyId,
  copyText,
  href,
  hrefLabel,
  copiedKey,
  onCopy,
}: {
  label: string;
  value: string;
  mono?: boolean;
  copyId?: string;
  copyText?: string;
  href?: string | null;
  hrefLabel?: string;
  copiedKey: string | null;
  onCopy: (text: string, key: string) => void;
}) {
  return (
    <div className="flex items-center justify-between gap-2 py-0.5">
      <span className="shrink-0 text-muted-foreground">{label}</span>
      <div className="flex min-w-0 items-center gap-1.5">
        <span
          className={cn(
            'truncate text-foreground',
            mono ? 'font-mono text-[11px] font-medium' : 'text-xs',
          )}
          title={value}
        >
          {value}
        </span>
        {copyId && copyText && (
          <CopyBtn text={copyText} id={copyId} copiedKey={copiedKey} onCopy={onCopy} />
        )}
        {href && <LinkBtn href={href} label={hrefLabel ?? '打开'} />}
      </div>
    </div>
  );
}

/** 状态圆点 */
function Dot({ color = 'emerald' }: { color?: 'emerald' | 'amber' | 'slate' }) {
  const cls =
    color === 'emerald' ? 'bg-emerald-500' : color === 'amber' ? 'bg-amber-400' : 'bg-slate-400';
  return <span className={cn('size-1.5 rounded-full', cls)} />;
}

